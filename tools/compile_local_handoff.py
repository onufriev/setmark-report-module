def validate() -> None:
    files = sorted(path.name for path in OUT.glob("*.md"))
    if files != sorted(EXPECTED):
        raise SystemExit(f"Ожидалось ровно девять файлов: {files}")
    for path in OUT.glob("*.md"):
        text = path.read_text(encoding="utf-8")
        if "Решение Product Manager" in text:
            raise SystemExit(f"Служебный заголовок попал в handoff: {path.name}")
        for target in re.findall(r"\[[^]]+\]\(([^)#]+\.md)(?:#[^)]+)?\)", text):
            if not (path.parent / target).resolve().exists():
                raise SystemExit(f"Некорректная ссылка {target} в {path.name}")


